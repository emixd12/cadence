// Builds the "Cadence day" view to one HTML file and writes it into the generated module
// that the MCP server serves: lib/mcp/apps/day-view-html.ts.
//
//   npm run mcp-views:build          rebuild and write the module
//   npm run mcp-views:check          rebuild and fail when the module differs by one byte
//
// The build runs in memory and writes no dist folder. It must be deterministic: the same
// sources and lockfile always give the same bytes (tests/mcp-day-view-build.test.ts).
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { gzipSync } from "node:zlib";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const check = process.argv.includes("--check");
const configFile = fileURLToPath(new URL("../vite.config.ts", import.meta.url));
const target = new URL("../../../lib/mcp/apps/day-view-html.ts", import.meta.url);
const targetLabel = "lib/mcp/apps/day-view-html.ts";

// The bytes must not depend on who runs the build: Vitest sets NODE_ENV=test, and a
// developer's shell or .env file may set anything.
process.env.NODE_ENV = "production";
const result = await build({ configFile, mode: "production", envFile: false, logLevel: "error", build: { write: false } });
const outputs = (Array.isArray(result) ? result : [result]).flatMap((entry) => entry.output);
const htmlFiles = outputs.filter((file) => file.fileName.endsWith(".html"));
if (htmlFiles.length !== 1 || outputs.length !== 1) {
  console.error(`Expected exactly one HTML file and nothing else; got: ${outputs.map((file) => file.fileName).join(", ")}`);
  process.exit(1);
}
const html = String(htmlFiles[0].source);

const moduleText = [
  "// Generated by `npm run mcp-views:build` from packages/mcp-views. Do not edit.",
  "// `npm run test` rebuilds the view and fails when this file differs by one byte.",
  `export const DAY_VIEW_HTML: string = ${JSON.stringify(html)};`,
  "",
].join("\n");

const raw = Buffer.byteLength(html);
const gzip = gzipSync(html, { level: 9 }).length;
const size = `${raw} bytes raw, ${gzip} bytes gzip`;

if (check) {
  const existing = await readFile(target, "utf8").catch(() => null);
  if (existing !== moduleText) {
    console.error(`${targetLabel} is out of date with packages/mcp-views. Run \`npm run mcp-views:build\` and commit the result.`);
    process.exit(1);
  }
  console.log(`${targetLabel} matches the build (${size}).`);
} else {
  await mkdir(new URL(".", target), { recursive: true });
  await writeFile(target, moduleText);
  console.log(`Wrote ${targetLabel} (${size}).`);
}
