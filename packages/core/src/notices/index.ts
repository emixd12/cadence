/**
 * The notices library: every sentence Cadence shows about what just happened or what
 * state something is in, one entry per notice (docs/NOTICES.md, generated by
 * `npm run map:build`). Each catalog file is one feature's notices. Code shows a notice
 * by its id, never by copying its text, so one edit here changes it everywhere.
 *
 * Styles (DESIGN.md, Nov 19 text styles):
 * - outcome: what an action did. Ink, italic; links inside stay upright.
 * - error: something failed or was refused. One Rust Signal line (the Alert notice).
 * - note: a small aside. Readable Ash, the only grey.
 * - question: asks the person to choose. Ink, upright.
 */

export type NoticeStyle = "outcome" | "error" | "note" | "question";
export type NoticeChannel = "in-app" | "reminder" | "email";
export type NoticeStatus = "active" | "planned" | "retired";
export type NoticePlatform = "web" | "mac";
export type NoticeAlertKind = "model_failed" | "data_stale" | "budget_reached" | "write_refused";

/** One earlier version, kept so a single change can be reverted (Emi, product map answer 1). */
export type NoticeRevision = Readonly<{
  /** The earlier text, when the words changed. */
  text?: string;
  /** The earlier look, in words, when the style changed. */
  look?: string;
  /** The last day the earlier version was shown. */
  until: string;
  /** What changed and why. */
  change: string;
}>;

export type NoticeEntry = Readonly<{
  meaning: string;
  text: string;
  style: NoticeStyle;
  /** For errors: the Alert notice kind, which sets how it is announced. */
  alert?: NoticeAlertKind;
  /** For errors: the short label before the sentence ("Not changed."). */
  label?: string;
  channel?: NoticeChannel;
  status?: NoticeStatus;
  /** Defaults to both. */
  platforms?: readonly NoticePlatform[];
  /** Defaults to the catalog file's feature. */
  feature?: string;
  interactions: readonly string[];
  previous?: readonly NoticeRevision[];
}>;

type Catalog = Readonly<{ feature: string; notices: Readonly<Record<string, NoticeEntry>> }>;

// JSON types widen `style` to string; the notices test and `npm run map:check` validate every entry.
const CATALOGS = [dailyBrief, dailyBriefMoves, endingPausingArchiving, moveForToday, opportunity, placeSearch, subBehaviors, timeline] as const;

type CatalogIds<C> = C extends { notices: infer N } ? keyof N & string : never;
export type NoticeId = CatalogIds<(typeof CATALOGS)[number]>;

export type ResolvedNotice = NoticeEntry & Readonly<{ id: NoticeId; feature: string }>;

export const NOTICES: Readonly<Record<NoticeId, ResolvedNotice>> = Object.freeze(Object.fromEntries(
  (CATALOGS as readonly Catalog[]).flatMap((catalog) => Object.entries(catalog.notices)
    .map(([id, entry]) => [id, Object.freeze({ ...entry, id, feature: entry.feature ?? catalog.feature })])),
) as Record<NoticeId, ResolvedNotice>);

export function isNoticeId(value: string): value is NoticeId {
  return Object.hasOwn(NOTICES, value);
}

export function noticeEntry(id: NoticeId): ResolvedNotice {
  return NOTICES[id];
}

/** The notice's sentence with its values filled in. */
export function noticeText(id: NoticeId, params?: NoticeParams): string {
  return formatNoticeTemplate(NOTICES[id].text, params);
}

